def hr():
    return HRFlowable(width="100%", thickness=0.5, color=black,
                      spaceBefore=2, spaceAfter=2)


def section_head(text, S):
    return [hr(), Paragraph(text, S["sec_title"])]


def sec_new(words, S):
    out = section_head("SECTION 1 — NEW ACQUISITIONS", S)
    for i, (word, pos, defn, ex) in enumerate(words):
        out.append(Paragraph(
            f"{word} <font name='Helvetica-Oblique' size='7'>{pos}</font>  "
            f"<font name='Helvetica' size='7.5'>{defn}</font>",
            S["word_name"]))
        out.append(Paragraph(f"<i>{ex}</i>", S["word_example"]))
    return out


def sec_recall(prev, day, S):
    out = section_head("SECTION 2 — 24-HOUR RECALL  (Fill in the Blank)", S)
    if not prev:
        out.append(Paragraph(f"Memory Tip: {MEMORY_TIPS[(day-1) % len(MEMORY_TIPS)]}", S["tip"]))
        return out
    for n, (word, _, _, ex) in enumerate(prev, 1):
        out.append(Paragraph(f"{n}. {blank_sentence(ex, word)}", S["exercise"]))
    return out


def sec_review(rev, day, S, body_w):
    out = section_head("SECTION 3 — 7-DAY DEEP REVIEW  (Match Definition → Word)", S)
    if not rev:
        out.append(Paragraph(f"Memory Tip: {MEMORY_TIPS[(day+2) % len(MEMORY_TIPS)]}", S["tip"]))
        return out
    rng = random.Random(day * 7)
    shuffled = list(rev)
    rng.shuffle(shuffled)
    letters = "ABCDE"
    rows = [["Definition", "Word Bank"]]
    for i, (word, _, defn, _) in enumerate(rev):
        rows.append([
            Paragraph(f"{i+1}. {defn}", S["exercise"]),
            Paragraph(f"{letters[i]}. {shuffled[i][0]}", S["exercise"]),
        ])
    tbl = Table(rows, colWidths=[body_w * 0.60, body_w * 0.40])
    tbl.setStyle(TableStyle([
        ("FONTNAME",      (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE",      (0, 0), (-1, 0), 8),
        ("LINEBELOW",     (0, 0), (-1, 0), 0.5, black),
        ("FONTNAME",      (0, 1), (-1, -1), "Helvetica"),
        ("FONTSIZE",      (0, 1), (-1, -1), 8),
        ("VALIGN",        (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING",    (0, 0), (-1, -1), 1),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 1),
        ("LEFTPADDING",   (0, 0), (-1, -1), 2),
        ("RIGHTPADDING",  (0, 0), (-1, -1), 2),
    ]))
    out.append(tbl)
    return out


def sec_mastery(mast, day, S):
    out = section_head("SECTION 4 — 30-DAY ULTIMATE TEST  (Synonym Challenge)", S)
    if not mast:
        out.append(Paragraph(f"Memory Tip: {MEMORY_TIPS[(day+5) % len(MEMORY_TIPS)]}", S["tip"]))
        return out
    for n, (word, _, defn, _) in enumerate(mast, 1):
        clue = next((w for w in defn.split() if len(w) > 4), defn.split()[0])
        out.append(Paragraph(f"{n}. Synonym for '<i>{clue}…</i>'  → ______________",
                             S["exercise"]))
    return out


def personal_box(words, S, width):
    w1 = words[0][0] if words else "Word 1"
    w2 = words[1][0] if len(words) > 1 else "Word 2"
    inner = [
        Paragraph("PERSONAL CONNECTION BOX", S["box_title"]),
        Spacer(1, 2),
        Paragraph(
            f"Write one sentence using both '<b>{w1}</b>' and '<b>{w2}</b>':",
            S["box_body"]),
        Spacer(1, 4),
        Paragraph("_ " * 28, S["box_body"]),
        Spacer(1, 3),
        Paragraph("_ " * 28, S["box_body"]),
    ]
    return DottedBox(inner, width=width, height=54, padding=5)


# ── Day page builder ───────────────────────────────────────────────────────────

def build_day(day, S, body_w):
    day_words  = get_words(day)
    prev_words = get_words(day - 1)
    rev_words  = get_words(day - 7)
    mast_words = get_words(day - 30)

    story = []
    story.append(Paragraph(f"DAY {day}", S["day_header"]))
    story.append(Paragraph("Date: ___________________________", S["date_line"]))
    story.extend(sec_new(day_words, S))
    story.extend(sec_recall(prev_words, day, S))
    story.extend(sec_review(rev_words, day, S, body_w))
    story.extend(sec_mastery(mast_words, day, S))
    story.append(Spacer(1, 2))
    story.append(personal_box(day_words, S, body_w))
    return story


# ── Front-matter helpers ───────────────────────────────────────────────────────

def make_styles_front():
    base = getSampleStyleSheet()
    title  = ParagraphStyle("fm_title",  parent=base["Title"],
                            fontName="Times-Bold",   fontSize=20,
                            leading=26, alignment=TA_CENTER, spaceAfter=10)
    sub    = ParagraphStyle("fm_sub",    parent=base["Normal"],
                            fontName="Times-Roman",  fontSize=12,
                            leading=15, alignment=TA_CENTER, spaceAfter=6)
    body   = ParagraphStyle("fm_body",   parent=base["Normal"],
                            fontName="Helvetica",    fontSize=9,
                            leading=13, spaceAfter=6)
    bhead  = ParagraphStyle("fm_bhead",  parent=base["Normal"],
                            fontName="Helvetica-Bold", fontSize=9,
                            leading=13, spaceAfter=2, spaceBefore=5)
    copy   = ParagraphStyle("fm_copy",   parent=base["Normal"],
                            fontName="Helvetica",    fontSize=8.5,
                            leading=12, alignment=TA_CENTER)
    head2  = ParagraphStyle("fm_head2",  parent=base["Normal"],
                            fontName="Helvetica-Bold", fontSize=12,
                            leading=15, alignment=TA_CENTER, spaceAfter=8)
    return title, sub, body, bhead, copy, head2


