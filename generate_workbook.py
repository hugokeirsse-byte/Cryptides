# ── Custom dotted-border flowable ──────────────────────────────────────────────

class DottedBox(Flowable):
    """Draws a dotted rectangle and places inline content inside it."""

    def __init__(self, content, width, height, padding=5):
        super().__init__()
        self._content  = content
        self.width     = width
        self.height    = height
        self._padding  = padding

    def wrap(self, aW, aH):
        return self.width, self.height

    def draw(self):
        from reportlab.platypus import Frame
        c = self.canv
        c.saveState()
        c.setDash(2, 3)
        c.setLineWidth(0.5)
        c.rect(0, 0, self.width, self.height, stroke=1, fill=0)
        c.restoreState()
        p = self._padding
        Frame(p, p, self.width - 2*p, self.height - 2*p,
              showBoundary=0).addFromList(list(self._content), c)

    def drawOn(self, canvas, x, y, _sW=0):
        self.canv = canvas
        canvas.saveState()
        canvas.translate(x, y)
        self.draw()
        canvas.restoreState()


