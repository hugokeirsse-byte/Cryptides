# ── Helper functions ───────────────────────────────────────────────────────────

def get_words(day, n=5):
    """Return n words for a given 1-based day; safe at boundaries."""
    if day < 1:
        return []
    start = (day - 1) * n
    return list(WORDS[start:start + n])


def blank_sentence(sentence, word):
    """Replace the first case-insensitive occurrence of word with underscores."""
    pattern = re.compile(re.escape(word), re.IGNORECASE)
    return pattern.sub("_" * max(8, len(word)), sentence, count=1)


